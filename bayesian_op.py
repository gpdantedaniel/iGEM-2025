def bayesian_optimization_pppl_first(max_mutations, has_indels: bool, sequence_type, call_id):
  seq_length = len(spycatcher_sequence) if sequence_type == "spycatcher" else len(spytag_sequence)
  search_space = []

  #Perform Bayesian optimization differently based on whether or not indels are permitted

  if has_indels:
    mut_type_list = ["substitution", "insertion", "deletion"]

    # Search space for Bayesian Optimization
    for i in range(max_mutations):
      search_space.append(Categorical(mut_type_list, name=f"mut_type{i}"))
      search_space.append(Integer(1, seq_length+1, name=f"pos{i}"))
      search_space.append(Categorical(aa_list, name=f"aa{i}"))

    if sequence_type == "spycatcher":
      blackbox_indels = compute_mutant_spycatcher_pppl
    else:
      blackbox_indels = compute_mutant_spytag_pppl

    res = gp_minimize(
     blackbox_indels, # compute_mutant_spycatcher_pppl/compute_mutant_spytag_pppl
     search_space,
     acq_func="gp_hedge",
     n_calls=num_calls
     )

  else:

    # Search space for Bayesian Optimization
    for i in range(max_mutations):
      search_space.append(Integer(1, seq_length+1, name=f"pos{i}"))
      search_space.append(Categorical(aa_list, name=f"aa{i}"))

    if sequence_type == "spycatcher":
      blackbox_subs = compute_mutant_spycatcher_pppl_subs
    else:
      blackbox_subs = compute_mutant_spytag_pppl_subs

    res = gp_minimize(
     blackbox_subs, # compute_mutant_spycatcher_pppl_subs/compute_mutant_spytag_pppl_subs
     search_space,
     acq_func="gp_hedge",
     n_calls=num_calls
     )

  # Generate convergence plot
  ax = plot_convergence(res)
  fig = ax.figure
  fig.set_size_inches(8, 5)
  fig.savefig(f'{call_id}.png')
  plt.close(fig)

  # Get mutations with top 5 lowest pppls
  all_mutations = res.x_iters
  all_pppls = res.func_vals

  sorted_pppl = sorted(zip(all_mutations, all_pppls), key=lambda x: x[1])
  top_5_pppls = sorted_pppl[:5]

  # Get ddGs of mutations with top 5 lowest pppls
  unsorted_ddGs = []
  ranked_pppls = []

  for i, (mutations, pppl) in enumerate(top_5_pppls, 1):
    processed_mutations = process_mutations(mutations) # Format list of mutations properly
    mutations = processed_mutations
    ranked_pppls.append((i, mutations))

    if sequence_type == "spycatcher":
      if has_indels:
        ddG = compute_mutant_spycatcher_ddG(mutations)
        mutated_sequence = mutate_protein(mutations, spycatcher_sequence, spycatcher_bans)
      else:
        ddG = compute_mutant_spycatcher_ddG_subs(mutations)
        mutated_sequence = mutate_protein_subs(mutations, spycatcher_sequence, spycatcher_bans)
    else: # sequence_type == "spytag"
      if has_indels:
        ddG = compute_mutant_spytag_ddG(mutations)
        mutated_sequence = mutate_protein(mutations, spytag_sequence, spytag_bans)
      else:
        ddG = compute_mutant_spytag_ddG_subs(mutations)
        mutated_sequence = mutate_protein_subs(mutations, spytag_sequence, spytag_bans)

    unsorted_ddGs.append((mutations, mutated_sequence, ddG))

  sorted_ddGs = sorted(unsorted_ddGs, key=lambda x: x[2])

  # Compute combined rank of ddG and pppl
  final_rank = []

  for i, (mutations_ddG, mutated_sequence, bans, ddG) in enumerate(sorted_ddGs, 1):
    for (rank, mutations_pppl) in ranked_pppls:
      if set(mutations_ddG) == set(mutations_pppl):
        final_rank.append((i + rank, mutations_ddG, mutated_sequence, bans))

  sorted_rank = sorted(final_rank)

  top_mutations = sorted_rank[0][1]
  top_sequence = sorted_rank[0][2]
  isopeptide_bond_index = [sorted_rank[0][3][0] + 1]

  output = []
  output.append(top_mutations)
  output.append(top_sequence)
  output.append(isopeptide_bond_index)

  output_string = f'{output[0]}\n{output[1]}\n{output[2]}'
 
  with open('bo_output.txt', 'a') as output_file:
    output_file.write(f'{call_id}:\n{output_string}\n') 

