def compute_ddG(mutant_sequence):
  # Check if mutate_protein returned a string, otherwise penalize
  if not isinstance(mutant_sequence, str):
      return 1000 # Penalize invalid mutations

  # Generate the embeddings for the WT and the MT sequences
  wild_embedding = embedding_model.encode(
    sentences=spycatcher_sequence,
    convert_to_tensor=True,
    normalize_emebddings=False
  ).to('cuda')

  mutant_embedding = embedding_model.encode(
    sentences=mutant_sequence,
    convert_to_tensor=True,
    normalize_emebddings=False
  ).to('cuda')

  # Run inference to calculate DDG
  ddG = regressor.forward(wild=wild_embedding, mut=mutant_embedding)

  return ddG.item()

