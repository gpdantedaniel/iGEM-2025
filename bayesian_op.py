import torch
import torch.nn as nn

class DDGPredictor8M(nn.Module):
    def __init__(self):
        super().__init__()
        self.head = nn.Sequential(
            nn.Linear(320, 512),
            nn.ReLU(),
            nn.Dropout(0.3),
            nn.Linear(512, 256),
            nn.ReLU(),
            nn.Linear(256, 1)
        )

    def forward(self, wild, mut):
        diff = mut - wild
        return self.head(diff).squeeze()

regressor = DDGPredictor8M().to('cuda')
