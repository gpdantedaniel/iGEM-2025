"""#4. Mutate sequence"""

def mutate_protein(mutations, sequence, bans):
  """
  Mutates sequence with the given mutations (substitutions, insertions, and deletions) and banned positions
  """

  #Apply mutations
  num_parameters = len(mutations)
  seen = set()

  for i in range (0, num_parameters, 3):
    # Extract information about mutation
    mut_type = mutations[i]
    mutation_index = mutations[i+1]- 1 # Amino acid sequences index from 1 but Python indexes from 0
    aa = mutations[i+2]

    # Edit the protein sequence based on the mutation type

    if mut_type == "substitution":

      # Flag substitutions whose index is past the length of the sequence
      if mutation_index == len(sequence):
        return 0

      if mutation_index not in seen and not (mutation_index in bans or (mutation_index == 0 and aa == "M")):
        seen.add(mutation_index)
        new_sequence = sequence[:mutation_index] + aa + sequence[mutation_index+1:]
        sequence = new_sequence

    elif mut_type == "deletion":

      # Flag deletions whose index is past the length of the sequence
      if mutation_index == len(sequence):
        return 0

      new_sequence = sequence[:mutation_index] + sequence[mutation_index+1:]
      sequence = new_sequence

      # Update banned positions
      if mutation_index < bans[0]:
        bans[0] -= 1
      if len(bans) > 1 and mutation_index < bans[1]:
        bans[1] -= 1

    else: # Insertion
      # Inserts in front of the amino acid of the given index
      new_sequence = sequence[:mutation_index] + aa + sequence[mutation_index:]
      sequence = new_sequence

      # Update banned positions
      if mutation_index < bans[0]:
        bans[0] += 1
      if len(bans) > 1 and mutation_index < bans[1]:
        bans[1] += 1

  return sequence

def mutate_protein_subs(mutations, sequence, banned_positions):
  """
  Mutates sequence with the given mutations (substitutions only) and banned positions,
  """
  #Apply mutations
  num_parameters = len(mutations)
  seen = set()

  for i in range(0, num_parameters, 2):
    pos = mutations[i]
    aa = mutations[i + 1]

    #Mutate the sequence
    mutation_index = mutations[i] - 1 # amino acid seqs index from 1 but Python indexes from 0
    aa = mutations[i + 1]

    if mutation_index not in seen and not (mutation_index in banned_positions or (mutation_index == 0 and aa == "M")):
      seen.add(mutation_index)
      new_sequence = sequence[:mutation_index] + aa + sequence[mutation_index+1:]
      sequence = new_sequence

  #Calculate pppl of mutated sequence
  return sequence

"""# 5. Calculate PPPL"""

def compute_pppl(protein_sequence):
  """
  Computes pseudoperplexity, given a sequence
  """
  if not(isinstance(protein_sequence, str)):
    return 1000
  input_ids = tokenizer(protein_sequence, return_tensors="pt").input_ids
  seq_len = input_ids.size(1)
  log_probs = []

  for i in range(1, seq_len - 1):  # skip <cls> and <eos>
    masked_input = input_ids.clone().to(device) # Copy to same device as model
    masked_input[0, i] = tokenizer.mask_token_id

    with torch.no_grad():
      outputs = model(input_ids=masked_input)
    logits = outputs.logits

    true_token_id = input_ids[0, i]
    logit = logits[0, i]
    log_prob = torch.log_softmax(logit, dim=-1)[true_token_id]
    log_probs.append(log_prob)

  return math.exp(-(torch.stack(log_probs).sum().item())/(seq_len-2))

def compute_mutant_spycatcher_pppl (mutations):
  """
  Returns: PPPL of spycatcher after a series of mutations
  Format of mutations: [mutation type 1, index 1, amino acid 1, mutation type 2, index 2, amino acid 2, ...]
  """
  new_sequence = mutate_protein(mutations, spycatcher_sequence, spycatcher_bans)

  # Punish mutations with incorrect indexing
  if not isinstance(new_sequence, str):
    return 1000  # penalty

  # Calculate pppl of mutated sequence
  pppl = compute_pppl(new_sequence)
  return pppl

